#!/usr/bin/env node
// Builds what the package ships from the repository's data:
//   data/snapshot.json.gz            the dated snapshot every tool reads
//   src/dogrulebook/vendor/match.mjs the hotel matcher, copied from src/lib
//
// Run from anywhere; it changes to the repository root because the data
// loader reads ./data relative to the working directory.
//
//   node packages/mcp/scripts/build.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(PKG, "..", "..");
process.chdir(ROOT);

const [
  { loadGraph },
  { getAnswers },
  { abs, brandPath, placePath },
  { ruleJson },
  { tagsOf },
  { site },
  { ROUTE_GUIDES },
  { buildSnapshot },
] = await Promise.all([
  import("../../../src/lib/data.mjs"),
  import("../../../src/lib/answers.mjs"),
  import("../../../src/lib/jsonld.mjs"),
  import("../../../src/lib/api.mjs"),
  import("../../../src/lib/filters.mjs"),
  import("../../../src/config/site.mjs"),
  import("../../../src/config/routes.mjs"),
  import("../src/snapshot/build.mjs"),
]);

const graph = loadGraph();
const snapshot = buildSnapshot(graph, {
  site,
  tagsOf,
  abs,
  placePath,
  brandPath,
  ruleJson,
  answers: getAnswers(graph),
  routeGuides: ROUTE_GUIDES,
});
const json = JSON.stringify(snapshot);
mkdirSync(join(PKG, "data"), { recursive: true });
const out = join(PKG, "data", "snapshot.json.gz");
// mtime 0 and level 9 keep the file byte-identical for identical data.
writeFileSync(out, gzipSync(json, { level: 9 }));
console.log(
  `snapshot ${snapshot.as_of}: ${snapshot.places.length} places, ${snapshot.brands.length} brands, ${Object.keys(snapshot.routes).length} routes, ${snapshot.answers.length} answers; ${(json.length / 1e6).toFixed(1)} MB raw -> ${out}`,
);

// Vendor the matcher: one source of truth in src/lib, a copy that needs no
// repository to run. The import it carries is replaced by the table it needs.
const source = readFileSync(join(ROOT, "src", "lib", "match.mjs"), "utf8");
const STAY_IMPORT = 'import { STAY } from "./format.mjs";';
if (!source.includes(STAY_IMPORT))
  throw new Error(
    "src/lib/match.mjs changed its imports; update packages/mcp/scripts/build.mjs",
  );
const vendored =
  `// GENERATED by packages/mcp/scripts/build.mjs from src/lib/match.mjs. Do not edit here.\n` +
  source.replace(STAY_IMPORT, 'import { STAY } from "../stay.mjs";');
mkdirSync(join(PKG, "src", "dogrulebook", "vendor"), { recursive: true });
writeFileSync(join(PKG, "src", "dogrulebook", "vendor", "match.mjs"), vendored);
console.log(
  "vendored src/lib/match.mjs -> packages/mcp/src/dogrulebook/vendor/match.mjs",
);
