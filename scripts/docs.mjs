#!/usr/bin/env node
// Writes docs/tools.md from the live tool, resource and prompt definitions,
// so the reference never drifts from the code. Run after changing a tool.
//
//   node scripts/docs.mjs

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as z from "zod/v4";
import { createRuntime, toolDefinitions } from "../src/dogpolicies/server.mjs";
import { resources } from "../src/dogpolicies/resources.mjs";
import { prompts } from "../src/dogpolicies/prompts.mjs";
import { PACKAGE_NAME, PACKAGE_VERSION } from "../src/config.mjs";

const ctx = createRuntime({
  env: {},
  overrides: { offline: true, logLevel: "silent" },
});
const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "docs",
  "tools.md",
);

const schemaRows = (schema) => {
  const json = z.toJSONSchema(schema, { io: "input", unrepresentable: "any" });
  const req = new Set(json.required ?? []);
  return Object.entries(json.properties ?? {}).map(([name, p]) => {
    const type = p.enum
      ? p.enum.map((v) => `\`${v}\``).join(", ")
      : p.type === "array"
        ? `array of ${p.items?.enum ? p.items.enum.map((v) => `\`${v}\``).join(", ") : (p.items?.type ?? "items")}`
        : (p.type ?? "object");
    const bounds = [
      p.minimum != null && `min ${p.minimum}`,
      p.maximum != null && `max ${p.maximum}`,
      p.minLength != null && `min length ${p.minLength}`,
      p.maxLength != null && `max length ${p.maxLength}`,
      p.default !== undefined && `default \`${JSON.stringify(p.default)}\``,
    ]
      .filter(Boolean)
      .join(", ");
    return `| \`${name}\`${req.has(name) ? " (required)" : ""} | ${type}${bounds ? ` (${bounds})` : ""} | ${(p.description ?? "").replaceAll("|", "\\|")} |`;
  });
};

const lines = [
  `# Tool reference`,
  "",
  `${PACKAGE_NAME} ${PACKAGE_VERSION}, generated by \`node scripts/docs.mjs\` from the live definitions. Every tool returns readable markdown by default and structured JSON with \`response_format: "json"\`; every result starts with a citation and ends with the attribution line.`,
  "",
];
for (const t of toolDefinitions(ctx)) {
  lines.push(
    `## \`${t.name}\``,
    "",
    `**${t.title}**${t.since ? ` · since ${t.since}` : ""}${t.deprecated ? ` · DEPRECATED: ${t.deprecated}` : ""}`,
    "",
  );
  lines.push(
    ...t.description
      .split("\n")
      .map((l) => (l.startsWith("  - ") ? l.trimStart() : l)),
    "",
  );
  const a = t.annotations;
  lines.push(
    `Annotations: read-only ${a.readOnlyHint}, destructive ${a.destructiveHint}, idempotent ${a.idempotentHint}, open-world ${a.openWorldHint}.`,
    "",
  );
  lines.push(
    "| Input | Type | Meaning |",
    "|---|---|---|",
    ...schemaRows(t.inputSchema),
    "",
  );
  if (t.outputSchema) {
    const json = z.toJSONSchema(t.outputSchema, {
      io: "output",
      unrepresentable: "any",
    });
    lines.push(
      `Output fields: ${Object.keys(json.properties ?? {})
        .map((k) => `\`${k}\``)
        .join(", ")} (more may be added; none removed).`,
      "",
    );
  }
}
lines.push("# Resources", "", "| URI | What | Type |", "|---|---|---|");
for (const r of resources(ctx))
  lines.push(
    `| \`${r.uri ?? r.template.uriTemplate}\` | ${r.description} | ${r.mimeType} |`,
  );
lines.push(
  "",
  "Templates support completion (`completion/complete`) for their variable.",
  "",
  "# Prompts",
  "",
  "| Name | What | Arguments |",
  "|---|---|---|",
);
for (const p of prompts(ctx))
  lines.push(
    `| \`${p.name}\` | ${p.description} | ${Object.keys(p.argsSchema ?? {})
      .map((k) => `\`${k}\``)
      .join(", ")} |`,
  );
lines.push("");
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}`);
